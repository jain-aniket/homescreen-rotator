private data class IntervalOption(val label: String, val hours: Float)

private val intervalOptions = listOf(
    IntervalOption("30 minutes", 0.5f),
    IntervalOption("1 hour", 1f),
    IntervalOption("3 hours", 3f),
    IntervalOption("6 hours", 6f),
    IntervalOption("12 hours", 12f),
    IntervalOption("Daily", 24f),
    IntervalOption("Weekly", 168f)
)

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun SettingsScreen(
    onNavigateBack: () -> Unit,
    viewModel: SettingsViewModel = viewModel()
) {
    val state by viewModel.uiState.collectAsState()
    val snackbarHostState = remember { SnackbarHostState() }

    LaunchedEffect(state.rotationMessage) {
        state.rotationMessage?.let {
            snackbarHostState.showSnackbar(it)
            viewModel.clearMessage()
        }
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("Settings") },
                navigationIcon = {
                    IconButton(onClick = onNavigateBack) {
                        Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Back")
                    }
                },
                colors = TopAppBarDefaults.topAppBarColors(
                    containerColor = MaterialTheme.colorScheme.surface
                )
            )
        },
        snackbarHost = { SnackbarHost(snackbarHostState) }
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .padding(horizontal = 16.dp)
                .verticalScroll(rememberScrollState()),
            verticalArrangement = Arrangement.spacedBy(16.dp)
        ) {
            Spacer(modifier = Modifier.height(8.dp))

            SectionCard(title = "Device Display") {
                InfoRow("Aspect Ratio", state.aspectRatioString)
                InfoRow("Resolution", "${state.screenWidth} x ${state.screenHeight}")
                InfoRow("Enabled Photos", "${state.enabledPhotoCount}")
            }

            SectionCard(title = "Rotation Schedule") {
                IntervalDropdown(
                    currentHours = state.intervalHours,
                    onIntervalSelected = { viewModel.setInterval(it) }
                )
            }

            SectionCard(title = "Triggers") {
                ToggleRow(
                    label = "Rotate on screen unlock",
                    checked = state.rotateOnUnlock,
                    onCheckedChange = { viewModel.setRotateOnUnlock(it) }
                )
                ToggleRow(
                    label = "Rotate on device boot",
                    checked = state.rotateOnBoot,
                    onCheckedChange = { viewModel.setRotateOnBoot(it) }
                )
            }

            Button(
                onClick = { viewModel.rotateNow() },
                modifier = Modifier.fillMaxWidth(),
                shape = RoundedCornerShape(12.dp)
            ) {
                Icon(Icons.Default.Refresh, contentDescription = null)
                Text("  Rotate Now", style = MaterialTheme.typography.labelLarge)
            }

            Spacer(modifier = Modifier.height(16.dp))
        }
    }
}

@Composable
private fun SectionCard(title: String, content: @Composable () -> Unit) {
    Card(
        modifier = Modifier.fillMaxWidth(),
        shape = RoundedCornerShape(16.dp),
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant)
    ) {
        Column(modifier = Modifier.padding(16.dp)) {
            Text(title, style = MaterialTheme.typography.titleMedium)
            Spacer(modifier = Modifier.height(12.dp))
            content()
        }
    }
}

@Composable
private fun InfoRow(label: String, value: String) {
    Row(
        modifier = Modifier
            .fillMaxWidth()
            .padding(vertical = 4.dp),
        horizontalArrangement = Arrangement.SpaceBetween
    ) {
        Text(label, style = MaterialTheme.typography.bodyMedium, color = MaterialTheme.colorScheme.onSurfaceVariant)
        Text(value, style = MaterialTheme.typography.bodyMedium)
    }
}

@Composable
private fun ToggleRow(label: String, checked: Boolean, onCheckedChange: (Boolean) -> Unit) {
    Row(
        modifier = Modifier
            .fillMaxWidth()
            .padding(vertical = 4.dp),
        horizontalArrangement = Arrangement.SpaceBetween,
        verticalAlignment = Alignment.CenterVertically
    ) {
        Text(label, style = MaterialTheme.typography.bodyMedium, modifier = Modifier.weight(1f))
        Switch(checked = checked, onCheckedChange = onCheckedChange)
    }
}

@OptIn(ExperimentalMaterial3Api::class)
@Composable
private fun IntervalDropdown(currentHours: Float, onIntervalSelected: (Float) -> Unit) {
    var expanded by remember { mutableStateOf(false) }
    val currentLabel = intervalOptions.find { it.hours == currentHours }?.label ?: "${currentHours}h"

    ExposedDropdownMenuBox(
        expanded = expanded,
        onExpandedChange = { expanded = !expanded }
    ) {
        OutlinedTextField(
            value = currentLabel,
            onValueChange = {},
            readOnly = true,
            label = { Text("Rotation Interval") },
            trailingIcon = { ExposedDropdownMenuDefaults.TrailingIcon(expanded = expanded) },
            modifier = Modifier
                .fillMaxWidth()
                .menuAnchor()
        )
        ExposedDropdownMenu(expanded = expanded, onDismissRequest = { expanded = false }) {
            intervalOptions.forEach { option ->
                DropdownMenuItem(
                    text = { Text(option.label) },
                    onClick = {
                        onIntervalSelected(option.hours)
                        expanded = false
                    }
                )
            }
        }
    }
}
